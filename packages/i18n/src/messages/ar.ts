/**
 * Arabic messages — the first translated locale after English.
 *
 * Written in formal Modern Standard Arabic, in the register of a business
 * application: the people reading it are office staff, company owners and
 * engineers on site, not consumers. Every key here mirrors `en.ts`; a test in
 * this package fails when the two drift apart.
 *
 * Two rules for anybody adding to this file:
 *
 * - **Translate the meaning, not the words.** English word order, idioms and
 *   fragments do not survive the trip. If an English string only makes sense
 *   beside another one, the two are one message in Arabic too.
 * - **Plurals carry every Arabic form.** Arabic distinguishes zero, one, two,
 *   a few (3–10), many (11–99) and other (100+, fractions). Where the English
 *   has `_one` and `_other`, the Arabic adds `_zero`, `_two`, `_few` and
 *   `_many` so a count of three reads as Arabic rather than falling back to
 *   English. The dual and the singular carry the number in the word, so
 *   `{{count}}` is deliberately absent from `_one` and `_two`.
 */

import type { Messages } from './en.js';

/**
 * A translation of `Messages`.
 *
 * `en.ts` is declared `as const`, so `Messages` holds each English sentence as
 * a literal type and nothing but English could satisfy it. This widens every
 * leaf to `string` while keeping the tree and its key names, so a missing or
 * misspelt key is still a compile error — and it permits the extra plural
 * suffixes Arabic needs for any key English pluralises.
 */
export type Catalogue<T> = {
  readonly [K in keyof T]: T[K] extends string ? string : Catalogue<T[K]>;
} & {
  readonly [
    K in keyof T as K extends `${infer Stem}_one`
      ? `${Stem}_zero` | `${Stem}_two` | `${Stem}_few` | `${Stem}_many`
      : never
  ]?: string;
};

